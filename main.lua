-- 多点RGB找色（范围找）：按 AREA[str] 数组逐点取色，全部点在误差 25 内返回 true
function rgbbj(str)
    local pts = AREA[str]
    if pts == nil then
        logStr("脚本错误，请截图或拍照这个提示给脚本管理，rgbbj错误内容:" .. tostring(str))
        error("rgbbj: 区域不存在: " .. tostring(str))
    end
    keepScreen(true)
    local ok = true
    for i = 1, #pts do
        local p = pts[i]  -- 每个元素是 {x, y, color}
        if not bj(p[1], p[2], p[3], 25) then
            ok = false
            break
        end
    end
    keepScreen(false)
    return ok
end

-- 多点找色（区域模板字符串）：按 AREA[str] = {x1, y1, x2, y2, colorsStr, sim} 找色
-- 匹配语义 = AutoGo images.FindMultiColors: 逐通道偏色，颜色支持 "RRGGBB-偏色" 后缀
function findArea(str)
    local t = AREA[str]
    if t == nil then
        error("findArea: 区域不存在: " .. tostring(str))
    end
    local x, y = findColors(t[1], t[2], t[3], t[4], t[5], t[6] or 0.9)
    return x ~= nil
end

-- 单点RGB找色（范围）：bj(x, y, color, err)，x/y 为脚本坐标，color 为 0xRRGGBB
function bj(x, y, color, err)
    local r, g, b = screen.getColorRGB(x, y)   -- 直接返回 0~255 的 RGB 分量
    local r1 = math.modf(color / 65536)
    local g1 = math.modf(color / 256) % 256
    local b1 = color % 256
    if math.abs(r - r1) <= err and math.abs(g - g1) <= err and math.abs(b - b1) <= err then
        return true
    end
    return false
end

